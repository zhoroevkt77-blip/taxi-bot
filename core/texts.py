# Узун тексттер сөз-сөз которулбайт — толук даяр варианты колдонулат
FULL_RU = {
    WELCOME: WELCOME_RU,
    GUIDE: GUIDE_RU,
    DRIVER_WARNING: DRIVER_WARNING_RU,
    FAQ_INTRO: FAQ_INTRO_RU,
    FAQ_POST: FAQ_POST_RU,
    FAQ_FREE: FAQ_FREE_RU,
    FAQ_SEARCH: FAQ_SEARCH_RU,
    FAQ_CONTACT: FAQ_CONTACT_RU,
    FAQ_SAFETY: FAQ_SAFETY_RU,
}

_RU_SORTED = sorted(RU.items(), key=lambda kv: -len(kv[0]))
_HTML_TAG_RE = re.compile(r"<[^>]+>")


def tr(text, lang):
    """Кыргызча текстти орусчага которот."""
    if lang != "ru" or not text:
        return text

    # Алгач толук даяр котормо барбы — ошону колдонобуз
    full = FULL_RU.get(text)
    if full:
        return full

    out = text
    for ky, ru in _RU_SORTED:
        if ky in out:
            out = out.replace(ky, ru)
    for ky, ru in RU_WORDS.items():
        out = re.sub(
            rf"(?<![а-яёөүңА-ЯЁӨҮҢ]){re.escape(ky)}(?![а-яёөүңА-ЯЁӨҮҢ])",
            ru, out
        )
    return out


def strip_html(text):
    """WhatsApp үчүн: <b>, <i> сыяктуу тегдерди алып салат."""
    if not text:
        return text
    out = _HTML_TAG_RE.sub("", text)
    return out.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")


def render(text, lang="ky", platform="telegram"):
    """Эки платформа үчүн акыркы даяр текстти чыгарат."""
    out = tr(text, lang)
    if platform == "whatsapp":
        out = strip_html(out)
    return out

